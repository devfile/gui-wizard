import { readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { expect, test } from '@playwright/test'
import Ajv from 'ajv'
import { buildDevfile, validateDevfile } from '../../src/utils/devfileGenerator'
import { fullCoverageState, fullCoverageStates } from './fixtures/devfile-states'

/**
 * Checks the wizard against the published devfile 2.3.0 JSON schema:
 *
 *  - everything it generates is accepted by the schema,
 *  - every field of the schema can be generated.
 *
 * The schema is vendored in `tests/schema` so the suite stays offline and
 * pinned to the version the wizard targets.
 */

const schemaPath = join(dirname(fileURLToPath(import.meta.url)), '..', 'schema', 'devfile-2.3.0.json')
const schema = JSON.parse(readFileSync(schemaPath, 'utf8'))

// `unicodeRegExp` is off because the published schema uses escapes (`\-`) that
// are not valid in unicode mode.
const ajv = new Ajv({ strict: false, allErrors: true, unicodeRegExp: false })
const validateAgainstSchema = ajv.compile(schema)

/** Every field the schema defines, as dotted paths with `[]` for list items. */
function schemaPaths(node, prefix = '') {
  const paths = []
  if (!node?.properties) return paths

  for (const [key, value] of Object.entries(node.properties)) {
    const path = prefix ? `${prefix}.${key}` : key

    if (value.type === 'array' && value.items?.properties) {
      paths.push(...schemaPaths(value.items, `${path}[]`))
    } else if (value.properties) {
      paths.push(...schemaPaths(value, path))
    } else {
      paths.push(path)
    }
  }

  return paths
}

/** Every field a generated devfile actually contains, in the same notation. */
function instancePaths(value, prefix = '', found = new Set()) {
  if (Array.isArray(value)) {
    for (const item of value) instancePaths(item, `${prefix}[]`, found)
    return found
  }

  if (value === null || typeof value !== 'object') return found

  for (const [key, child] of Object.entries(value)) {
    const path = prefix ? `${prefix}.${key}` : key
    found.add(path)
    instancePaths(child, path, found)
  }

  return found
}

test.describe('devfile 2.3.0 schema', () => {
  test('the vendored schema is the 2.3.0 one', () => {
    expect(schema.title).toBe('Devfile schema - Version 2.3.0')
  })

  test('generated devfiles validate against the schema', () => {
    for (const state of fullCoverageStates()) {
      const devfile = buildDevfile(state)
      const valid = validateAgainstSchema(devfile)

      expect(
        valid,
        `schema errors: ${JSON.stringify(validateAgainstSchema.errors, null, 2)}`
      ).toBe(true)
    }
  })

  test('the full coverage devfiles raise no error and no warning', () => {
    for (const state of fullCoverageStates()) {
      const { errors, warnings } = validateDevfile(state)

      expect(errors).toEqual([])
      expect(warnings).toEqual([])
    }
  })

  test('every field of the schema can be generated by the wizard', () => {
    const generated = new Set()
    for (const state of fullCoverageStates()) {
      instancePaths(buildDevfile(state), '', generated)
    }

    const missing = schemaPaths(schema).filter((path) => !generated.has(path))

    expect(missing, `fields the wizard never generates: ${missing.join(', ')}`).toEqual([])
  })

  test('the wizard never generates a field the schema does not define', () => {
    const allowed = new Set(schemaPaths(schema))

    // Free-form maps hold user defined keys, their contents are not described
    // by the schema.
    const freeForm = [
      /(^|\.)attributes(\.|$)/,
      /(^|\.)variables\./,
      /(^|\.)remotes\./,
      /(^|\.)annotation\./,
      /^metadata\.generateName$/
    ]

    for (const state of fullCoverageStates()) {
      const devfile = buildDevfile(state)
      const unknown = [...instancePaths(devfile)].filter(
        (path) => !allowed.has(path) && !freeForm.some((pattern) => pattern.test(path))
      )

      // Paths of intermediate objects and lists are reported by
      // `instancePaths` but are not leaves of the schema, so only unknown
      // leaves are left here.
      const unexpected = unknown.filter(
        (path) =>
          ![...allowed].some(
            (allowedPath) => allowedPath.startsWith(`${path}.`) || allowedPath.startsWith(`${path}[]`)
          )
      )

      expect(unexpected, `fields outside the schema: ${unexpected.join(', ')}`).toEqual([])
    }
  })

  test('a devfile the wizard accepts is also accepted by the schema', () => {
    // The constraints the schema puts on values (patterns, enums, lengths and
    // bounds), each broken in the place the wizard could emit it. Whatever the
    // wizard lets through here has to stay valid for the schema: a rule that
    // is only checked at the top level, or not at all, shows up as a failure.
    const containerOf = (component) => component.container
    const breakages = {
      'component name': (state) => {
        state.components[0].name = 'Not A Name'
      },
      'volume mount name': (state) => {
        state.components.find(containerOf).container.volumeMounts[0].name = 'Not A Name'
      },
      'long volume mount name': (state) => {
        state.components.find(containerOf).container.volumeMounts[0].name = 'm'.repeat(64)
      },
      'override volume mount name': (state) => {
        state.parent.components.find(containerOf).container.volumeMounts[0].name = 'Not A Name'
      },
      'endpoint name': (state) => {
        state.components.find(containerOf).container.endpoints[0].name = 'Not An Endpoint'
      },
      'override endpoint name': (state) => {
        state.parent.components.find(containerOf).container.endpoints[0].name = 'way-too-long-endpoint'
      },
      'endpoint protocol': (state) => {
        state.components.find(containerOf).container.endpoints[0].protocol = 'ftp'
      },
      'endpoint exposure': (state) => {
        state.components.find(containerOf).container.endpoints[0].exposure = 'everyone'
      },
      'command id': (state) => {
        state.commands[0].id = 'Not An Id'
      },
      'override command id': (state) => {
        state.parent.commands[0].id = 'Not An Id'
      },
      'command group kind': (state) => {
        state.commands[0].exec.group.kind = 'lint'
      },
      'project name': (state) => {
        state.projects[0].name = 'Not A Name'
      },
      'override project name': (state) => {
        state.parent.starterProjects[0].name = 'Not A Name'
      },
      'metadata version': (state) => {
        state.metadata.version = 'version one'
      },
      'metadata architecture': (state) => {
        state.metadata.architectures = ['sparc']
      },
      'schema version': (state) => {
        state.schemaVersion = '1.0.0'
      },
      'parent version': (state) => {
        // `version` only goes with a registry id.
        state.parent.uri = null
        state.parent.id = 'java-quarkus'
        state.parent.registryUrl = 'https://registry.devfile.io'
        state.parent.version = '0.1.0'
      }
    }

    for (const [what, breakIt] of Object.entries(breakages)) {
      const state = fullCoverageState()
      breakIt(state)

      expect(
        validateAgainstSchema(buildDevfile(state)),
        `the fixture for a broken ${what} is not a schema violation, the case proves nothing`
      ).toBe(false)

      expect(
        validateDevfile(state).errors,
        `the schema rejects a broken ${what}, the wizard reports no error`
      ).not.toEqual([])
    }
  })

  test('a devfile the wizard rejects is also rejected by the schema', () => {
    const [state] = fullCoverageStates()
    state.components[0].container.endpoints[0].targetPort = ''

    const { errors } = validateDevfile(state)
    expect(errors.join('\n')).toContain('targetPort is required')

    expect(validateAgainstSchema(buildDevfile(state))).toBe(false)
  })
})
